import { jsPDF } from 'jspdf';
import { autoTable } from 'jspdf-autotable';
import * as XLSX from 'xlsx';
import { formatINR, formatDate, formatTime, getCategoryInfo, calculateTotals } from './utils';

// Load and register Noto Sans fonts with jsPDF for ₹ symbol support
async function registerNotoSansFont(doc) {
  const loadFont = async (url, filename, fontName, fontStyle) => {
    const response = await fetch(url);
    const buffer = await response.arrayBuffer();
    const base64 = btoa(
      new Uint8Array(buffer).reduce((data, byte) => data + String.fromCharCode(byte), '')
    );
    doc.addFileToVFS(filename, base64);
    doc.addFont(filename, fontName, fontStyle);
  };

  await Promise.all([
    loadFont('/fonts/NotoSans-Regular.ttf', 'NotoSans-Regular.ttf', 'NotoSans', 'normal'),
    loadFont('/fonts/NotoSans-Bold.ttf', 'NotoSans-Bold.ttf', 'NotoSans', 'bold'),
  ]);

  doc.setFont('NotoSans', 'normal');
}

export async function exportToPDF(transactions, dateRange) {
  const doc = new jsPDF();

  // Register Noto Sans font for ₹ symbol support
  await registerNotoSansFont(doc);

  const { totalIncome, totalExpense, netBalance } = calculateTotals(transactions);

  // Header
  doc.setFontSize(22);
  doc.setTextColor(99, 102, 241); // indigo
  doc.text('SpendWise', 14, 22);

  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139); // slate
  doc.text('Expense Report', 14, 30);

  // Date range
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  doc.text(`Period: ${dateRange.label}`, 14, 40);
  doc.text(`Generated: ${formatDate(new Date().toISOString())}`, 14, 47);

  // Summary cards
  const summaryY = 55;
  
  // Income box
  doc.setFillColor(220, 252, 231);
  doc.roundedRect(14, summaryY, 55, 22, 3, 3, 'F');
  doc.setFontSize(9);
  doc.setTextColor(22, 163, 74);
  doc.text('Total Income', 18, summaryY + 9);
  doc.setFontSize(13);
  doc.text(formatINR(totalIncome), 18, summaryY + 18);

  // Expense box
  doc.setFillColor(254, 226, 226);
  doc.roundedRect(75, summaryY, 55, 22, 3, 3, 'F');
  doc.setFontSize(9);
  doc.setTextColor(220, 38, 38);
  doc.text('Total Expenses', 79, summaryY + 9);
  doc.setFontSize(13);
  doc.text(formatINR(totalExpense), 79, summaryY + 18);

  // Net box
  const netColor = netBalance >= 0 ? [22, 163, 74] : [220, 38, 38];
  doc.setFillColor(netBalance >= 0 ? 220 : 254, netBalance >= 0 ? 252 : 226, netBalance >= 0 ? 231 : 226);
  doc.roundedRect(136, summaryY, 60, 22, 3, 3, 'F');
  doc.setFontSize(9);
  doc.setTextColor(...netColor);
  doc.text('Net Balance', 140, summaryY + 9);
  doc.setFontSize(13);
  doc.text(`${netBalance >= 0 ? '+' : '-'}${formatINR(Math.abs(netBalance))}`, 140, summaryY + 18);

  // Transaction table
  const tableData = transactions
    .sort((a, b) => new Date(b.date) - new Date(a.date))
    .map((t) => [
      formatDate(t.date),
      formatTime(t.date),
      t.type === 'income' ? 'Income' : 'Expense',
      t.category ? getCategoryInfo(t.category).label : '-',
      t.description || '-',
      `${t.type === 'expense' ? '-' : '+'}${formatINR(t.amount)}`,
    ]);

  autoTable(doc, {
    startY: summaryY + 30,
    head: [['Date', 'Time', 'Type', 'Category', 'Description', 'Amount']],
    body: tableData,
    theme: 'striped',
    headStyles: {
      fillColor: [99, 102, 241],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 9,
      font: 'NotoSans',
    },
    bodyStyles: {
      fontSize: 8,
      textColor: [30, 41, 59],
      font: 'NotoSans',
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    columnStyles: {
      0: { cellWidth: 25 },
      1: { cellWidth: 18 },
      2: { cellWidth: 18 },
      3: { cellWidth: 30 },
      5: { cellWidth: 28, halign: 'right' },
    },
    didParseCell: function (data) {
      if (data.column.index === 5 && data.section === 'body') {
        const text = data.cell.raw;
        if (text.startsWith('-')) {
          data.cell.styles.textColor = [220, 38, 38];
        } else {
          data.cell.styles.textColor = [22, 163, 74];
        }
        data.cell.styles.fontStyle = 'bold';
      }
      if (data.column.index === 2 && data.section === 'body') {
        const text = data.cell.raw;
        if (text === 'Expense') {
          data.cell.styles.textColor = [220, 38, 38];
        } else {
          data.cell.styles.textColor = [22, 163, 74];
        }
      }
    },
    margin: { left: 14, right: 14 },
  });

  // Page numbers
  const pageCount = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      `Page ${i} of ${pageCount}`,
      doc.internal.pageSize.width / 2,
      doc.internal.pageSize.height - 10,
      { align: 'center' }
    );
    doc.text(
      'Generated by SpendWise',
      doc.internal.pageSize.width - 14,
      doc.internal.pageSize.height - 10,
      { align: 'right' }
    );
  }

  doc.save(`SpendWise_Report_${dateRange.label.replace(/[^a-zA-Z0-9]/g, '_')}.pdf`);
}

export function exportToExcel(transactions, dateRange) {
  const { totalIncome, totalExpense, netBalance } = calculateTotals(transactions);

  const data = transactions
    .sort((a, b) => new Date(b.date) - new Date(a.date))
    .map((t) => ({
      Date: formatDate(t.date),
      Time: formatTime(t.date),
      Type: t.type === 'income' ? 'Income' : 'Expense',
      Category: t.category ? getCategoryInfo(t.category).label : '-',
      Description: t.description || '-',
      Amount: t.type === 'expense' ? -Number(t.amount) : Number(t.amount),
    }));

  // Add summary rows
  data.push({});
  data.push({ Date: 'SUMMARY', Description: 'Total Income', Amount: totalIncome });
  data.push({ Description: 'Total Expenses', Amount: -totalExpense });
  data.push({ Description: 'Net Balance', Amount: netBalance });

  const ws = XLSX.utils.json_to_sheet(data);

  // Set column widths
  ws['!cols'] = [
    { wch: 14 },  // Date
    { wch: 10 },  // Time
    { wch: 10 },  // Type
    { wch: 18 },  // Category
    { wch: 30 },  // Description
    { wch: 16 },  // Amount
  ];

  // Format amount column as Indian currency
  const range = XLSX.utils.decode_range(ws['!ref']);
  for (let R = range.s.r + 1; R <= range.e.r; R++) {
    const cell = ws[XLSX.utils.encode_cell({ r: R, c: 5 })];
    if (cell && typeof cell.v === 'number') {
      cell.z = '₹#,##0.00';
    }
  }

  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'Expense Report');

  // Add a summary sheet
  const summaryData = [
    { Metric: 'Report Period', Value: dateRange.label },
    { Metric: 'Generated On', Value: formatDate(new Date().toISOString()) },
    { Metric: 'Total Transactions', Value: transactions.length },
    { Metric: 'Total Income', Value: totalIncome },
    { Metric: 'Total Expenses', Value: totalExpense },
    { Metric: 'Net Balance', Value: netBalance },
  ];

  const summaryWs = XLSX.utils.json_to_sheet(summaryData);
  summaryWs['!cols'] = [{ wch: 20 }, { wch: 20 }];
  XLSX.utils.book_append_sheet(wb, summaryWs, 'Summary');

  XLSX.writeFile(wb, `SpendWise_Report_${dateRange.label.replace(/[^a-zA-Z0-9]/g, '_')}.xlsx`);
}